  `econ1` STRING COMMENT 'Budget line field \'econ1\' as uploaded',
  `econ2` STRING COMMENT 'Budget line field \'econ2\' as uploaded',
  `econ3` STRING COMMENT 'Budget line field \'econ3\' as uploaded',
  `econ4` STRING COMMENT 'Budget line field \'econ4\' as uploaded',
  `prog1` STRING COMMENT 'Budget line field \'prog1\' as uploaded',
  `prog2` STRING COMMENT 'Budget line field \'prog2\' as uploaded',
  `amount` DOUBLE COMMENT 'Budget amount in `currency` (units as uploaded)',
  `climate_tag` STRING COMMENT 'GREEN | NEUTRAL | BROWN | AMBIGUOUS',
  `confidence` STRING COMMENT 'HIGH | MEDIUM | LOW',
  `tag_method` STRING COMMENT 'Which rule decided, e.g. RIO_MARKER, RIO_PREDETERMINED, RIO_EXCLUSION',
  `environmental_objective` STRING COMMENT 'mitigation | adaptation | ... | none',
  `subcategory` STRING COMMENT 'principal | significant | taxonomy_aligned | NULL',
  `rationale` STRING COMMENT 'Plain-language reason, including the matched keyword',
  `rio_marker` INT COMMENT 'Combined Rio Marker: 0 none, 1 significant, 2 principal',
  `rio_mitigation` INT COMMENT 'Rio Marker for mitigation (0/1/2)',
  `rio_adaptation` INT COMMENT 'Rio Marker for adaptation (0/1/2)',
  `currency` STRING COMMENT 'Currency code or label entered by the analyst',
  `data_source` STRING COMMENT 'Where the budget data came from (free text)',
  `notes` STRING COMMENT 'Analyst notes for this upload',
  `source_file` STRING COMMENT 'File name as uploaded',
  `source_row` INT COMMENT '1-based row number in the data sheet (header = row 1)',
  `content_hash` STRING COMMENT 'Fingerprint of the stored values for this (country, year, batch)',
  `methodology_version` STRING COMMENT 'Version of the keyword lists / rules',
  `uploaded_at` TIMESTAMP COMMENT 'UTC time the batch was saved',
  `deactivated_at` TIMESTAMP COMMENT 'UTC time validity became FALSE (NULL = never active or still active)',
  `deactivation_reason` STRING COMMENT 'replaced | deleted | discarded',
  `replaced_by` STRING COMMENT 'batch_id of the version that replaced this one (reason = replaced)'
) USING DELTA COMMENT 'Climate budget tagging - Rio Markers (0/1/2) per budget line. One row per source line; validity=TRUE marks the current version for a (country_iso3, year).' TBLPROPERTIES ('delta.autoOptimize.optimizeWrite' = 'true', 'delta.autoOptimize.autoCompact' = 'true');

